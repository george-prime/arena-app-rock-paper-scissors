// ROCK PAPER SCISSORS' MANIFEST VERSION 5, SIGNED BY ITS DEVELOPER: version 4 in every term but its client - client/index-v5.html
// (everything drawn by React, written by tools/build-client-v5.mjs). The core is version 4's (plugin/decide-v4.js). Parent: version 4
// (plugin/rock-paper-scissors-v4.js).
//
//   node packages/rock-paper-scissors/tools/sign-manifest-v5.mjs <dev dir holding game-dev.pkcs8>
//
// Writes only public bytes: plugin/rock-paper-scissors-v5.js.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { createHash } from 'node:crypto';
import { gameDevKey, signManifest } from 'arena-sdk/manifest-sign';
import { MANIFEST_V4, GAME_ID_V4 } from '../plugin/rock-paper-scissors-v4.js';
import { encodeManifest, gameIdOf, manifestStands } from 'arena-sdk/manifest';
import { toHex } from 'arena-sdk/hash';
import { verifyEd25519 } from 'arena-sdk/ed25519';

const [dir] = process.argv.slice(2);
if (!dir) { console.error('usage: node sign-manifest-v5.mjs <dev dir holding game-dev.pkcs8>'); process.exit(2); }
const dev = gameDevKey(readFileSync(join(dir, 'game-dev.pkcs8')));
if (toHex(dev.pubkey) !== toHex(MANIFEST_V4.gameDevPubkey)) throw new Error(`that key is not Rock Paper Scissors' developer key ${toHex(MANIFEST_V4.gameDevPubkey).slice(0, 16)}`);
const hash = (u) => new Uint8Array(createHash('sha256').update(readFileSync(u)).digest());
const CORE = hash(new URL('../plugin/decide-v4.js', import.meta.url));
const CLIENT = hash(new URL('../client/index-v5.html', import.meta.url));
const { signature, ...v4body } = MANIFEST_V4;
void signature;
if (MANIFEST_V4.cores.length !== 1) throw new Error('version 4 names one core');
if (toHex(MANIFEST_V4.cores[0].hash) !== toHex(CORE)) throw new Error('version 5 keeps version 4\'s core');
const body = { ...v4body, version: MANIFEST_V4.version + 1, parentManifestId: GAME_ID_V4, clients: [CLIENT] };
const manifest = signManifest(body, dev);
const stands = manifestStands(manifest, { verify: verifyEd25519, parentOf: (id) => (toHex(id) === toHex(GAME_ID_V4) ? MANIFEST_V4 : null) });
if (!stands.ok) throw new Error(stands.why);
const id = toHex(gameIdOf(manifest));
writeFileSync(new URL('../plugin/rock-paper-scissors-v5.js', import.meta.url), `// GENERATED by tools/sign-manifest-v5.mjs with the developer's signer - do not edit by hand. PUBLIC BYTES ONLY.
// rock-paper-scissors' GameManifest version 5: version 4 (${toHex(GAME_ID_V4)}) in every term but its client
// ${toHex(CLIENT)} (client/index-v5.html); its core is version 4's ${toHex(CORE)} (plugin/decide-v4.js); requires protocol version
// ${body.requiredProtocolVersion}. Signed by its developer key ${toHex(dev.pubkey)}; a node verifies it and never signs.
// game_id ${id}
import { GAME as V4, RPS_DECIDE_V4_CORE, RPS_ROUND_FIELDS_V4 } from './rock-paper-scissors-v4.js';
import { decodeManifest, gameIdOf } from 'arena-sdk/manifest';
import { fromHex } from 'arena-sdk/hash';

export const MANIFEST_V5_HEX = '${toHex(encodeManifest(manifest))}';
export const MANIFEST_V5 = decodeManifest(fromHex(MANIFEST_V5_HEX));
export const GAME_ID_V5 = gameIdOf(MANIFEST_V5);
export const RPS_CLIENT_V5_FILE = new URL('../client/index-v5.html', import.meta.url);
/** What a launcher loads from this module (ARENA_APPS): the registration, version 4's core and its client version 5's. */
export const GAME = Object.freeze({ ...V4, manifest: MANIFEST_V5, gameId: GAME_ID_V5, cores: new Map([[RPS_DECIDE_V4_CORE.hash, RPS_DECIDE_V4_CORE]]), clientUrls: [RPS_CLIENT_V5_FILE.href] });
/** A version-5 round's fields: its game, version 4's core and config and timing. */
export const RPS_ROUND_FIELDS_V5 = Object.freeze({ ...RPS_ROUND_FIELDS_V4, gameId: GAME_ID_V5 });
`);
console.log(`rock-paper-scissors v${body.version}: parent ${toHex(GAME_ID_V4).slice(0, 16)}, core ${toHex(CORE).slice(0, 12)}, client ${toHex(CLIENT).slice(0, 12)}, game_id ${id}`);
